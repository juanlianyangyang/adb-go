var (
	tempPrivKey *rsa.PrivateKey
	keyMutex    sync.RWMutex
)

// SetEmbeddedPrivKeyBytes 设置默认密钥
func SetEmbeddedPrivKeyBytes(keyBytes []byte) {
	embeddedPrivKeyBytes = keyBytes
}

// LoadOrGeneratePrivateKey 多级密钥加载器。
// 按优先级从以下来源加载或生成 RSA 私钥：
// 1. 内存缓存（保证单次进程内密钥一致）
// 2. 硬编码的嵌入密钥（embeddedPrivKeyBytes）
// 3. 本地文件 adbkey.pem
// 4. 生成新的 2048 位 RSA 密钥
//
// autoGen 参数：如果为 true，则跳过硬编码字节和本地文件，强制生成新密钥。
func LoadOrGeneratePrivateKey(autoGen bool) (*rsa.PrivateKey, error) {
	keyMutex.RLock()
	if tempPrivKey != nil {
		keyMutex.RUnlock()
		return tempPrivKey, nil
	}
	keyMutex.RUnlock()

	keyMutex.Lock()
	defer keyMutex.Unlock()

	if tempPrivKey != nil {
		return tempPrivKey, nil
	}

	const keyFilePath = "adbkey.pem"

	if !autoGen {
		if len(embeddedPrivKeyBytes) > 0 {
			privKey, err := x509.ParsePKCS1PrivateKey(embeddedPrivKeyBytes)
			if err == nil {
				tempPrivKey = privKey
				LogInfof("从嵌入式密钥加载成功")
				return privKey, nil
			}
			LogWarnf("解析嵌入式密钥失败: %v", err)
		}

		fileBytes, err := os.ReadFile(keyFilePath)
		if err == nil {
			block, _ := pem.Decode(fileBytes)
			if block != nil && block.Type == "RSA PRIVATE KEY" {
				privKey, err := x509.ParsePKCS1PrivateKey(block.Bytes)
				if err == nil {
					tempPrivKey = privKey
					LogInfof("从文件 %s 加载密钥成功", keyFilePath)
					return privKey, nil
				}
				LogWarnf("解析文件 %s 失败: %v", keyFilePath, err)
			}
		}
	} else {
		LogInfof("[测试模式] autoGen=true，跳过本地密钥检查")
	}

	LogInfof("正在生成新的 2048 位 RSA 密钥...")
	privKey, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		return nil, fmt.Errorf("生成新密钥失败: %w", err)
	}

	if !autoGen {
		pemBlock := &pem.Block{
			Type:  "RSA PRIVATE KEY",
			Bytes: x509.MarshalPKCS1PrivateKey(privKey),
		}
		err = os.WriteFile(keyFilePath, pem.EncodeToMemory(pemBlock), 0644)
		if err != nil {
			LogWarnf("无法保存密钥到文件 %s: %v", keyFilePath, err)
		} else {
			LogInfof("新密钥已保存到 %s", keyFilePath)
		}
	} else {
		LogInfof("临时密钥生成完毕，仅存在于内存中")
	}

	tempPrivKey = privKey
	return privKey, nil
}
